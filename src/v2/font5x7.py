def width(s, scale=1, sp=1):
    return sum((len(G.get(c, G[' '])[0]) + sp) * scale for c in s) - sp * scale
def draw(img, x, y, s, col, scale=1, sp=1):
    px = img.load()
    for c in s.upper():
        g = G.get(c, G[' '])
        off = (len(g) - 7) * scale
        for j, row in enumerate(g):
            for i, b in enumerate(row):
                if b == '1':
                    for a in range(scale):
                        for bb in range(scale):
                            X, Y = x + i * scale + a, y - off + j * scale + bb
                            if 0 <= X < img.width and 0 <= Y < img.height:
                                px[X, Y] = col
        x += (len(g[0]) + sp) * scale
